        public static void Draw(SpriteBatch batch, Texture2D pixel, string text, int x, int y, int size, Color color)
        {
            foreach (char c in text.ToUpperInvariant())
            {
                string glyph;
                if (Glyphs.TryGetValue(c, out glyph))
                    for (int row = 0; row < 7; row++)
                        for (int col = 0; col < 5; col++)
                            if (glyph[row * 6 + col] == '1')
                                batch.Draw(pixel, new Rectangle(x + col * size, y + row * size, size, size), color);
                x += 6 * size;
            }
        }
    }
